static uint8_t fb[EPD_SIZE];

static void fb_set_pixel(int x, int y, int on)
{
	if (x < 0 || x >= EPD_WIDTH || y < 0 || y >= EPD_HEIGHT)
		return;
	int byte = (y * EPD_WIDTH + x) / 8;
	int bit = 7 - (x % 8); /* MSB first */
	if (on)
		fb[byte] |= (1 << bit);
	else
		fb[byte] &= ~(1 << bit);
}

static int get_font_row(uint16_t glyph_row, int ch)
{
	if (ch < 0x20 || ch > 0x7E) ch = ' ';
	int idx = ch - 0x20;
	return font_8x16[idx * 16 + glyph_row];
}

